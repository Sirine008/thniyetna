"""Evaluate the RAG assistant on data/rag/eval/questions.jsonl.

    python -m rag.evaluate --variant baseline        # see VARIANTS
    python -m rag.evaluate --variant combined --ids q01,q11
    python -m rag.evaluate --report-only             # rebuild docs/RAG_EVALUATION.md (e.g. after labelling)

Run on the host from backend/ (the api container mounts data/rag read-only):
    $env:DATABASE_URL = "postgresql+psycopg://...@localhost:5433/thniyetna"; $env:OLLAMA_URL = "http://localhost:11434"

Same retrieval / prompt / chat functions as POST /assistant/ask, with the variant's settings passed
explicitly (the config defaults are not changed). Nothing is written to rag_queries (user log).
Writes data/rag/eval/results_<variant>.json and rebuilds the table in docs/RAG_EVALUATION.md from
all results files.

Metrics: retrieval hit@1 / hit@4 / MRR@4 on answerable questions (hit = expected document, and one of
the expected pages when given, or an `also_accepted` source); refusal rate on answerable (lower is
better); correct-refusal rate on unanswerable (higher is better); citation present and expected source
cited, over the non-refused answerable answers; median latency (translation + retrieval + generation).
Answer correctness is labelled by hand in the results files (record "label": correct | partial | wrong).
"""
import argparse
import json
import re
import statistics
import sys
import time
import unicodedata
from datetime import datetime
from pathlib import Path

from . import config, ollama
from .prompt import REFUSAL, build_messages

ROOT = Path(__file__).resolve().parents[2]
EVAL_DIR = ROOT / "data" / "rag" / "eval"
REPORT = ROOT / "docs" / "RAG_EVALUATION.md"

_BASE = {"bilingual": False, "prompt": "v1", "numbers_rule": False, "model": "llama3.2:3b", "fts": "simple",
         "context": False, "min_similarity": 0.0, "ids": None}
VARIANTS = {   # report order
    "baseline":        {**_BASE},
    "bilingual":       {**_BASE, "bilingual": True},
    "prompt_v2":       {**_BASE, "prompt": "v2"},
    "combined":        {**_BASE, "bilingual": True, "prompt": "v2"},
    "combined_gemma4": {**_BASE, "bilingual": True, "prompt": "v2", "model": "gemma4",
                        "ids": ["q02", "q06", "q11", "q16", "q19"], "compare_with": "combined"},
    # French-only users from here on: bilingual stays off; each step adds one fix to prompt_v2
    "fts_french":      {**_BASE, "prompt": "v2", "fts": "french"},
    "chunk_context":   {**_BASE, "prompt": "v2", "fts": "french", "context": True},
    "confidence_gate": {**_BASE, "prompt": "v2", "fts": "french", "context": True, "min_similarity": 0.0},
    "numbers_rule":    {**_BASE, "prompt": "v2", "numbers_rule": True, "fts": "french", "context": True,
                        "min_similarity": 0.0},
}
EVAL_CHAT_OPTIONS = {**config.CHAT_OPTIONS, "seed": 42}   # reproducible runs, same settings otherwise
LABELS = ("correct", "partial", "wrong")

REPORT_HEADER = """# RAG assistant — evaluation

Generated by `python -m rag.evaluate` (backend/rag/evaluate.py) from `data/rag/eval/results_*.json`.
Audience = field users (equipment / transport supervisors); only the field corpus (`data/rag/corpus/`) is
indexed. Questions: `data/rag/eval/questions.jsonl` (answerable questions with an expected document/page, plus
questions with no answer in the corpus). Embeddings: nomic-embed-text; top-k = 4; Ollama seed 42.

- **hit@1 / hit@4 / MRR@4**: the expected document (and page, when given; or another source listed as
  containing the same answer) is the first / among the 4 retrieved sources; MRR = mean of 1/rank (0 if absent).
  Answerable questions only.
- **Refusal (answerable)**: share of answerable questions answered with the refusal sentence — lower is better.
- **Correct refusal (unanswerable)**: share of unanswerable questions refused — higher is better.
- **Correct / partial / wrong**: manual reading of each non-refused answer to an answerable question against
  the source (labels by Claude, to be checked by Sirine; stored as `label` in the results files).
  correct + partial + wrong + refused = answerable questions.
- **Citation present / expected source cited**: over non-refused answerable answers, the answer cites a valid
  [n] / cites the expected document (and page).
- **FTS**: full-text configuration (`simple` or `french` = stemming). **Context**: retrieval on title +
  heading + chunk text. **Gate**: minimum cosine similarity of the best vector match, else refusal.
- **Latency**: median seconds per question (translation + retrieval + generation), host CPU, Ollama on the host.

With 16 answerable questions, one question changes a rate by about 6 points.

| Variant | Date | LLM | Bilingual | FTS | Context | Gate | Prompt | Questions | hit@1 | hit@4 | MRR@4 | Refusal (answerable) ↓ | Correct refusal (unanswerable) ↑ | Correct / partial / wrong (answerable) | Citation present | Expected source cited | Median latency (s) |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
"""


def load_questions(path: Path = EVAL_DIR / "questions.jsonl") -> list[dict]:
    rows = [json.loads(ln) for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    return [r for r in rows if "_meta" not in r]


def _matches(src: dict, q: dict) -> bool:
    """Expected document (and page, when given), or one of the `also_accepted` sources with the same answer."""
    targets = [{"document": q["expected_document"], "pages": q["expected_pages"]}] + q.get("also_accepted", [])
    return any(src["title"] == t["document"] and (not t["pages"] or src["page"] in t["pages"]) for t in targets)


def hit_rank(sources: list[dict], q: dict) -> int | None:
    """1-based rank of the first source matching the expected (or an accepted) document and page, None if absent."""
    return next((i for i, s in enumerate(sources, start=1) if _matches(s, q)), None)


def _norm(s: str) -> str:
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return " ".join(re.findall(r"[a-z0-9]+", s))


def is_refusal(answer: str) -> bool:
    """The refusal sentence anywhere in the answer, or no answer at all."""
    return not answer.strip() or _norm(REFUSAL) in _norm(answer)


def citations(answer: str, n_sources: int) -> list[int]:
    """Valid source numbers cited as [n] (also [1, 2] / [1][2]), in order of first appearance."""
    out = []
    for group in re.findall(r"\[([\d,\s]+)\]", answer):
        for n in re.findall(r"\d+", group):
            n = int(n)
            if 1 <= n <= n_sources and n not in out:
                out.append(n)
    return out


def _rate(num: int, den: int) -> dict:
    return {"value": round(num / den, 4) if den else None, "num": num, "den": den}


def summarize(records: list[dict]) -> dict:
    ans = [r for r in records if r["answerable"]]
    unans = [r for r in records if not r["answerable"]]
    answered = [r for r in ans if not r["refused"]]
    ranks = [r["hit_rank"] for r in ans]
    labels = [r.get("label") for r in answered]
    return {
        "n_answerable": len(ans), "n_unanswerable": len(unans),
        "hit_at_1": _rate(sum(r == 1 for r in ranks), len(ans)),
        "hit_at_4": _rate(sum(r is not None and r <= 4 for r in ranks), len(ans)),
        "mrr_at_4": round(sum(1 / r for r in ranks if r) / len(ans), 4) if ans else None,
        "refusal_on_answerable": _rate(sum(r["refused"] for r in ans), len(ans)),
        "correct_refusal_on_unanswerable": _rate(sum(r["refused"] for r in unans), len(unans)),
        "labels": {k: labels.count(k) for k in LABELS} | {"unlabelled": sum(lb not in LABELS for lb in labels)},
        "citation_present": _rate(sum(bool(r["cited"]) for r in answered), len(answered)),
        "expected_source_cited": _rate(sum(r["cited_expected"] for r in answered), len(answered)),
        "median_latency_s": round(statistics.median(r["latency_ms"] for r in records) / 1000, 1) if records else None,
        "errors": sum(bool(r.get("error")) for r in records),
    }


GATE_RULE = ("midpoint between the lowest best-similarity of an answerable question whose expected source is "
             "retrieved (hit@4) and the highest best-similarity of an unanswerable question")


def gate_threshold(records: list[dict]) -> dict:
    """Fixed, explainable rule, no search over values: see GATE_RULE."""
    ok = [r["best_similarity"] for r in records if r["answerable"] and r["hit_rank"] and r["best_similarity"] is not None]
    no = [r["best_similarity"] for r in records if not r["answerable"] and r["best_similarity"] is not None]
    if not ok or not no:
        return {"threshold": None, "lowest_answerable_hit": min(ok, default=None), "highest_unanswerable": max(no, default=None)}
    lo, hi = min(ok), max(no)
    return {"threshold": round((lo + hi) / 2, 4), "lowest_answerable_hit": lo, "highest_unanswerable": hi,
            "separable": lo > hi}


def gate_outcomes(records: list[dict], thresholds: dict[str, float]) -> list[dict]:
    """Outcome of each question if the gate (per-question threshold) were applied to these ungated records:
    gated -> refusal; otherwise the record's own answer (same retrieval and prompt)."""
    out = []
    for r in records:
        t = thresholds[r["id"]]
        gated = t is not None and (r["best_similarity"] is None or r["best_similarity"] < t)
        out.append({**r, "gated": gated, "refused": gated or r["refused"],
                    "label": None if gated else r.get("label"), "cited": [] if gated else r["cited"],
                    "cited_expected": False if gated else r["cited_expected"]})
    return out


def gate_study(records: list[dict]) -> dict:
    """In-sample threshold (gate_threshold on all records) and leave-one-out: for each question k the
    threshold is chosen without k, then applied to k."""
    full = gate_threshold(records)
    loo = {r["id"]: gate_threshold([x for x in records if x["id"] != r["id"]])["threshold"] for r in records}
    ins = gate_outcomes(records, {r["id"]: full["threshold"] for r in records})
    out = gate_outcomes(records, loo)
    per_q = [{"id": r["id"], "answerable": r["answerable"], "hit": bool(r["hit_rank"]),
              "best_similarity": r["best_similarity"], "loo_threshold": loo[r["id"]],
              "gated_in_sample": a["gated"], "gated_loo": b["gated"]} for r, a, b in zip(records, ins, out)]
    return {"rule": GATE_RULE, **full, "in_sample": summarize(ins), "leave_one_out": summarize(out),
            "per_question": per_q}


def _fmt(rate: dict) -> str:
    return "—" if rate["value"] is None else f"{rate['value']:.2f} ({rate['num']}/{rate['den']})"


def _fmt_labels(lb: dict) -> str:
    if lb["unlabelled"]:
        return f"not labelled ({lb['unlabelled']})"
    return f"{lb['correct']} / {lb['partial']} / {lb['wrong']}"


def report_row(label: str, settings: dict, summary: dict, date: str) -> str:
    st, s = {**_BASE, **settings}, summary
    gate = f"{st['min_similarity']:.2f}" if st["min_similarity"] > 0 else "off"
    cells = [label, date, st["model"], "on" if st["bilingual"] else "off", st["fts"],
             "on" if st["context"] else "off", gate, st["prompt"] + (" + numbers" if st["numbers_rule"] else ""),
             f"{s['n_answerable']} + {s['n_unanswerable']}", _fmt(s["hit_at_1"]), _fmt(s["hit_at_4"]),
             "—" if s["mrr_at_4"] is None else f"{s['mrr_at_4']:.2f}", _fmt(s["refusal_on_answerable"]),
             _fmt(s["correct_refusal_on_unanswerable"]), _fmt_labels(s["labels"]), _fmt(s["citation_present"]),
             _fmt(s["expected_source_cited"]), f"{s['median_latency_s']}"]
    if s["errors"]:
        cells[0] += f" ({s['errors']} error(s))"
    return "| " + " | ".join(cells) + " |\n"


def write_report(path: Path = REPORT) -> None:
    """Rebuild the whole table from the results files, in VARIANTS order (summaries recomputed, so labels count)."""
    rows = []
    for name, settings in VARIANTS.items():
        f = EVAL_DIR / f"results_{name}.json"
        if not f.exists():
            continue
        res = json.loads(f.read_text(encoding="utf-8"))
        rows.append(report_row(f"`{name}`", res["settings"], summarize(res["records"]), res["date"]))
        ref = settings.get("compare_with")
        ref_file = EVAL_DIR / f"results_{ref}.json"
        if ref and ref_file.exists():   # same question ids, for a like-for-like comparison
            ids = {r["id"] for r in res["records"]}
            ref_res = json.loads(ref_file.read_text(encoding="utf-8"))
            ref_recs = [r for r in ref_res["records"] if r["id"] in ids]
            rows.append(report_row(f"`{ref}` on the same {len(ref_recs)} ids", ref_res["settings"],
                                   summarize(ref_recs), ref_res["date"]))
    missing = [f"`{n}`" for n in VARIANTS if not (EVAL_DIR / f"results_{n}.json").exists()]
    pending = f"\nNot run yet: {', '.join(missing)}.\n" if missing else ""
    path.write_text(REPORT_HEADER + "".join(rows) + pending + gate_section(), encoding="utf-8", newline="\n")


GATE_FILE = EVAL_DIR / "gate_threshold.json"


def gate_section() -> str:
    if not GATE_FILE.exists():
        return ""
    g = json.loads(GATE_FILE.read_text(encoding="utf-8"))
    st = {**_BASE, **VARIANTS[g["source_variant"]]}
    head = ("| Gate threshold | Refusal (answerable) ↓ | Correct refusal (unanswerable) ↑ "
            "| Correct / partial / wrong (answerable) |\n|---|---|---|---|\n")

    def row(name: str, s: dict) -> str:
        return (f"| {name} | {_fmt(s['refusal_on_answerable'])} | {_fmt(s['correct_refusal_on_unanswerable'])} "
                f"| {_fmt_labels(s['labels'])} |\n")
    changed = [q for q in g["per_question"] if q["gated_in_sample"] != q["gated_loo"]]
    sims = ", ".join(f"{q['id']} {q['best_similarity'] or 0:.3f}{'' if q['answerable'] else ' (unanswerable)'}"
                     f"{' (miss)' if q['answerable'] and not q['hit'] else ''}"
                     for q in sorted(g["per_question"], key=lambda q: q["best_similarity"] or 0))
    return f"""
## Confidence gate threshold

**Tuned on the evaluation set.** The threshold is chosen on these 20 questions, which are also the test
questions, so the in-sample result is optimistic. A larger, independent question set is needed to confirm it.

- Rule (fixed in advance, no search over values): {g['rule']}.
- Computed on `{g['source_variant']}` (fts {st['fts']}, context {'on' if st['context'] else 'off'}, prompt {st['prompt']}):
  lowest answerable hit = {g['lowest_answerable_hit']}, highest unanswerable = {g['highest_unanswerable']}
  → **threshold = {g['threshold']}** ({'the two groups are separated' if g.get('separable') else 'the two groups overlap: some answerable questions with a retrieved source are below the highest unanswerable one'}).
- Outcomes below are derived from the `{g['source_variant']}` answers: a gated question becomes a refusal, the
  others keep their answer and label. Leave-one-out: for each question k, the threshold is recomputed without k
  and applied to k.

{head}{row(f"in-sample ({g['threshold']})", g['in_sample'])}{row("leave-one-out", g['leave_one_out'])}
Questions whose gate decision changes under leave-one-out: {', '.join(q['id'] + f" (LOO threshold {q['loo_threshold']})" for q in changed) or 'none'}.

Best similarity per question (ascending): {sims}.
"""


def evaluate_one(db, q: dict, settings: dict) -> dict:
    from .retrieve import passes_gate, retrieve_scored
    from .translate import translate

    st = {**_BASE, **settings}
    rec = {"id": q["id"], "lang": q["lang"], "answerable": q["answerable"], "question": q["question"]}
    t0 = time.perf_counter()
    best, gated = None, False
    try:
        sources, best = retrieve_scored(db, q["question"], bilingual=st["bilingual"], model=st["model"],
                                        fts=st["fts"], context=st["context"])
        gated = not passes_gate(best, st["min_similarity"])
        if gated:
            sources = []
        answer = (ollama.chat(build_messages(q["question"], sources, st["prompt"], st["numbers_rule"]),
                              model=st["model"], options=EVAL_CHAT_OPTIONS)
                  if sources else f"{REFUSAL}.")
        error = None
    except ollama.OllamaUnavailable:
        raise
    except ollama.OllamaError as exc:  # e.g. timeout answer from the server: recorded, run continues
        sources, answer, error = [], "", str(exc)
    rec["latency_ms"] = int((time.perf_counter() - t0) * 1000)
    if st["bilingual"]:
        rec["translation"] = translate(q["question"], st["model"])   # cached: no extra call
    cited = citations(answer, len(sources))
    rec.update({
        "best_similarity": best, "gated": gated,
        "sources": [{"n": s["n"], "title": s["title"], "page": s["page"], "chunk_id": s["chunk_id"],
                     "score": s["score"]} for s in sources],
        "hit_rank": hit_rank(sources, q) if q["answerable"] else None,
        "answer": answer, "refused": is_refusal(answer), "cited": cited,
        "cited_expected": bool(q["answerable"] and any(_matches(sources[n - 1], q) for n in cited)),
        "error": error,
    })
    return rec


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Evaluate the RAG assistant")
    ap.add_argument("--variant", choices=list(VARIANTS))
    ap.add_argument("--ids", help="comma-separated question ids (default: the variant's set)")
    ap.add_argument("--questions", type=Path, default=EVAL_DIR / "questions.jsonl")
    ap.add_argument("--no-report", action="store_true", help="do not rebuild docs/RAG_EVALUATION.md")
    ap.add_argument("--report-only", action="store_true", help="only rebuild docs/RAG_EVALUATION.md")
    ap.add_argument("--gate-from", metavar="VARIANT",
                    help="choose the confidence-gate threshold from an ungated variant's results (+ leave-one-out)")
    args = ap.parse_args(argv)
    if args.gate_from:
        res = json.loads((EVAL_DIR / f"results_{args.gate_from}.json").read_text(encoding="utf-8"))
        study = {"source_variant": args.gate_from, "source_date": res["date"], **gate_study(res["records"])}
        GATE_FILE.write_text(json.dumps(study, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
        print(json.dumps({k: v for k, v in study.items() if k != "per_question"}, indent=2))
        write_report()
        print(f"-> {GATE_FILE.relative_to(ROOT)}, {REPORT.relative_to(ROOT)}")
        return 0
    if args.report_only:
        write_report()
        print(f"-> {REPORT.relative_to(ROOT)}")
        return 0
    if not args.variant:
        ap.error("--variant is required (or --report-only)")

    settings = VARIANTS[args.variant]
    ids = args.ids.split(",") if args.ids else settings["ids"]
    questions = [q for q in load_questions(args.questions) if ids is None or q["id"] in ids]
    print(f"RAG eval '{args.variant}': {len(questions)} question(s), {settings['model']}, "
          f"bilingual={settings['bilingual']}, fts={settings['fts']}, context={settings['context']}, "
          f"gate={settings['min_similarity']}, prompt={settings['prompt']}, numbers_rule={settings['numbers_rule']}, "
          f"Ollama {config.OLLAMA_URL}")

    try:  # load the models before timing anything
        ollama.embed(["warm-up"], kind="query")
        ollama.chat([{"role": "user", "content": "OK"}], model=settings["model"], options={"num_predict": 1})
    except ollama.OllamaUnavailable as exc:
        print(f"Ollama unreachable: {exc}", file=sys.stderr)
        return 2

    from shared.db import SessionLocal
    records = []
    with SessionLocal() as db:
        for q in questions:
            rec = evaluate_one(db, q, settings)
            records.append(rec)
            flag = "REFUSED" if rec["refused"] else f"cites {rec['cited']}"
            print(f"  {q['id']} rank={rec['hit_rank']} sim={rec['best_similarity']} {flag} {rec['latency_ms'] / 1000:.1f}s")

    date = datetime.now().strftime("%Y-%m-%d %H:%M")
    summary = summarize(records)
    out = {"variant": args.variant, "date": date, "settings": settings, "chat_options": EVAL_CHAT_OPTIONS,
           "embed_model": config.RAG_EMBED_MODEL, "top_k": config.TOP_K, "summary": summary, "records": records}
    out_path = EVAL_DIR / f"results_{args.variant}.json"
    out_path.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(summary, indent=2))
    print(f"-> {out_path.relative_to(ROOT)}")
    if not args.no_report:
        write_report()
        print(f"-> {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
