"""Generate the model card (markdown for humans, JSON for GET /prediction/model).

    python -m prediction.report --md ../docs/M2_MODEL_CARD.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from .config import GOV_NAME_FR, MODEL_DIR, REPORT_DIR


def _r(x, n=3):
    return None if x is None else round(float(x), n)


def build_card() -> dict:
    rep = json.loads((REPORT_DIR / "training_report.json").read_text())
    cl = rep["classification"]
    chosen = cl["chosen"]
    card = {
        "model": f"m2-risk:{rep['version']}",
        "granularity": "governorate x day (Mode A) -> segment by exposure thinning + M1 events (Mode B)",
        "data": rep["data"],
        "chosen_classifier": chosen,
        "accident_flag_test": {k: _r(v, 4) for k, v in cl["final_calibrated_test"].items()},
        "candidates_test": {k: {m: _r(v["test"][m], 4) for m in ("roc_auc", "pr_auc", "f1")} for k, v in cl["candidates"].items()},
        "naive_rate30_test": {m: _r(cl["naive_rate30_test"][m], 4) for m in ("roc_auc", "pr_auc", "f1")},
        "count_model": rep["regression"]["chosen"],
        "count_test": {k: {m: _r(v["test"][m], 4) for m in ("mae", "rmse", "r2")} for k, v in rep["regression"]["candidates"].items()},
        "fatal_test": {m: _r(rep["fatal"]["test"][m], 4) for m in ("base_rate", "roc_auc", "pr_auc")},
        "road_class_weights": rep["road_class_weights"],
        "mlflow_run_id": rep.get("mlflow_run_id"),
    }
    abl = REPORT_DIR / "ablation.csv"
    if abl.exists():
        card["ablation"] = pd.read_csv(abl).round(4).to_dict("records")
    pg = REPORT_DIR / "test_metrics_per_governorate.csv"
    if pg.exists():
        d = pd.read_csv(pg)
        card["within_governorate_roc_auc_median"] = _r(d["roc_auc"].median())
    return card


def to_markdown(card: dict) -> str:
    t = card["accident_flag_test"]
    d = card["data"]
    lines = [
        f"# M2 model card — `{card['model']}`", "",
        "Generated by `python -m prediction.report` from `reports/m2/`. Do not edit by hand.", "",
        "## Task",
        "Predict, for each governorate and day, the probability of at least one recorded road accident",
        "(`accident_flag`), the expected number of accidents and the probability of a fatal accident.",
        "Segment RiskScores are derived from these forecasts (see `segment_risk.py`).", "",
        "## Data",
        f"- Accidents: {d['accidents_rows']:,} records, {d['accidents_first']} → {d['accidents_last']} (no GPS; governorate on every record).",
        f"- Weather: one reference station, {d['weather_first']} → {d['weather_last']}.",
        f"- Panel: {d['panel_rows']:,} governorate-days, {d['panel_start']} → {d['panel_end']}.",
        f"- Temporal split: train ≤ {d['split']['train_end']}, validation ≤ {d['split']['val_end']}, test → {d['split']['test_end']}. No random split.",
        "- Every feature of day t is computed from data up to t-1 (unit-tested in `tests/test_m2_core.py`).", "",
        "## Results on the test period",
        f"Chosen classifier: **{card['chosen_classifier']}** (a tree model replaces it only if validation PR-AUC improves by ≥ 0.005).", "",
        "| Model | ROC-AUC | PR-AUC | F1 |", "|---|---|---|---|",
    ]
    for k, v in card["candidates_test"].items():
        lines.append(f"| {k} | {v['roc_auc']} | {v['pr_auc']} | {v['f1']} |")
    n = card["naive_rate30_test"]
    lines += [f"| naive 30-day rate | {n['roc_auc']} | {n['pr_auc']} | {n['f1']} |", "",
              f"Deployed (Platt-calibrated) model: ROC-AUC {t['roc_auc']}, PR-AUC {t['pr_auc']}, F1 {t['f1']} at threshold {t['threshold']} "
              f"(precision {t['precision']}, recall {t['recall']}), Brier {t['brier']}, base rate {t['base_rate']}.", "",
              "| Count model | MAE | RMSE | R² |", "|---|---|---|---|"]
    for k, v in card["count_test"].items():
        lines.append(f"| {k} | {v['mae']} | {v['rmse']} | {v['r2']} |")
    f = card["fatal_test"]
    lines += ["", f"Fatal-accident classifier: PR-AUC {f['pr_auc']} for a base rate of {f['base_rate']} (ROC-AUC {f['roc_auc']}).", ""]
    if "ablation" in card:
        lines += ["## Ablation (test PR-AUC)", "", "| Variant | PR-AUC | Δ vs all |", "|---|---|---|"]
        for r in card["ablation"]:
            lines.append(f"| {r['variant']} | {r['pr_auc']} | {r['delta_pr_auc_vs_all']:+.4f} |")
        lines.append("")
    lines += [
        "## What the results mean (limits)",
        f"- The model mainly separates *which governorates* are risky; within one governorate the median ROC-AUC is "
        f"{card.get('within_governorate_roc_auc_median')} — day-to-day timing is close to unpredictable with these inputs.",
        "- Accident history carries almost all the signal. With one national weather station, weather features add nothing "
        "(see ablation); per-governorate weather (`fetch_weather.py`) is the next experiment.",
        "- Trees (RF, XGBoost) do not beat the logistic regression significantly at this granularity.",
        "- Segment-level accident risk is an *allocation* (exposure × class weight), not a segment-level model: "
        "accidents have no coordinates. It ranks road classes and lengths correctly but cannot single out a black spot.",
        "- The M1 condition component is a documented rule-based prior until labelled defect histories exist (`condition_model.py`).",
        "- The accident export ends before the scoring date: history features use the last observed day and the API reports "
        "`history_staleness_days`.", "",
        "## Road-class weights (accident rate per km, relative)", "",
        "| Class | Weight |", "|---|---|",
    ]
    for k, v in card["road_class_weights"].items():
        lines.append(f"| {k} | {v} |")
    lines += ["", f"MLflow run: `{card.get('mlflow_run_id')}`", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", default=None)
    args = ap.parse_args(argv)
    card = build_card()
    (MODEL_DIR / "model_card.json").write_text(json.dumps(card, indent=2, ensure_ascii=False, default=str))
    md = to_markdown(card)
    out = Path(args.md) if args.md else REPORT_DIR / "MODEL_CARD.md"
    out.write_text(md, encoding="utf-8")
    print(f"[card] {out}")


if __name__ == "__main__":
    main()
